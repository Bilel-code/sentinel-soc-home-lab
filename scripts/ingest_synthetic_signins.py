"""
Synthetic sign-in log generator and ingestion script.

Simulates three distinct attack patterns against sign-in telemetry, each
mapped to a MITRE ATT&CK technique, and pushes the synthetic JSON records
into a custom Log Analytics table via the Azure Monitor Logs Ingestion API:

  1. Brute force (T1110.001)      - many failed attempts against ONE
                                     account from ONE IP, then a success.
  2. Password spray (T1110.003)   - a FEW failed attempts against MANY
                                     different accounts from ONE IP.
  3. Impossible travel (T1078)    - two successful sign-ins for the SAME
                                     account from two different locations,
                                     too close together in time to be real
                                     travel.

All data generated by this script is synthetic / self-generated for a
personal SOC home-lab exercise. No real user accounts, IP addresses, or
credentials are involved.

Auth: uses AzureCliCredential, i.e. whichever account you're signed into via
`az login`. That account must hold the "Monitoring Metrics Publisher" role
on the target Data Collection Rule (see README in this repo for how that
role assignment was set up).

Usage:
    pip install azure-identity azure-monitor-ingestion
    az login
    az account set --subscription "Azure for Students"
    python ingest_synthetic_signins.py
"""

import datetime
import sys

from azure.identity import AzureCliCredential
from azure.monitor.ingestion import LogsIngestionClient
from azure.core.exceptions import HttpResponseError

# ---- Configuration -----------------------------------------------------
# Values specific to this lab's Data Collection Endpoint / Rule / table.
DCE_ENDPOINT = "https://dce-sentinel-lab-mv25.francecentral-1.ingest.monitor.azure.com"
DCR_IMMUTABLE_ID = "dcr-f6356b4f338f474186ea4ef6b8ccfc96"

# Confirm this against the DCR's "streamDeclarations" key (Export template /
# JSON view in the portal) before running. It is usually "Custom-<TableName>".
STREAM_NAME = "Custom-SyntheticSignins_CL"

SYNTHETIC_APP = "Office 365 Exchange Online"


def _iso(base_time: datetime.datetime, offset_seconds: int) -> str:
    return (base_time + datetime.timedelta(seconds=offset_seconds)).strftime(
        "%Y-%m-%dT%H:%M:%SZ"
    )


def generate_bruteforce_logs() -> list[dict]:
    """Scenario 1: Brute force (MITRE T1110.001).

    4 failed sign-ins ~17 seconds apart, then 1 success, all from the same
    source IP and user account.
    """
    base_time = datetime.datetime.now(datetime.timezone.utc)
    user = "j.carter@contoso-lab.com"
    source_ip = "185.220.101.47"

    events = []
    for i in range(4):
        events.append(
            {
                "TimeGenerated": _iso(base_time, i * 17),
                "UserPrincipalName": user,
                "SourceIP": source_ip,
                "ResultType": "Failure",
                "ResultDescription": "Invalid username or password",
                "Location": "Unknown",
                "AppDisplayName": SYNTHETIC_APP,
            }
        )

    events.append(
        {
            "TimeGenerated": _iso(base_time, 4 * 17),
            "UserPrincipalName": user,
            "SourceIP": source_ip,
            "ResultType": "Success",
            "ResultDescription": "Sign-in succeeded",
            "Location": "Unknown",
            "AppDisplayName": SYNTHETIC_APP,
        }
    )

    return events


def generate_password_spray_logs() -> list[dict]:
    """Scenario 2: Password spray (MITRE T1110.003).

    One source IP making a single failed attempt against each of several
    different accounts, staying under any one account's lockout threshold -
    then one of those guesses lands, producing a success on the last
    account. Distinguishes "low and slow, many accounts" from brute force's
    "many attempts, one account".
    """
    base_time = datetime.datetime.now(datetime.timezone.utc)
    source_ip = "91.219.237.244"
    accounts = [
        "m.chen@contoso-lab.com",
        "r.patel@contoso-lab.com",
        "s.okafor@contoso-lab.com",
        "l.garcia@contoso-lab.com",
        "a.novak@contoso-lab.com",
    ]

    events = []
    for i, account in enumerate(accounts[:-1]):
        events.append(
            {
                "TimeGenerated": _iso(base_time, i * 25),
                "UserPrincipalName": account,
                "SourceIP": source_ip,
                "ResultType": "Failure",
                "ResultDescription": "Invalid username or password",
                "Location": "Unknown",
                "AppDisplayName": SYNTHETIC_APP,
            }
        )

    # Last account: the spray lands.
    events.append(
        {
            "TimeGenerated": _iso(base_time, len(accounts) * 25),
            "UserPrincipalName": accounts[-1],
            "SourceIP": source_ip,
            "ResultType": "Success",
            "ResultDescription": "Sign-in succeeded",
            "Location": "Unknown",
            "AppDisplayName": SYNTHETIC_APP,
        }
    )

    return events


def generate_impossible_travel_logs() -> list[dict]:
    """Scenario 3: Impossible travel (MITRE T1078).

    Two successful sign-ins for the same account, from two different
    locations/IPs, ~4 minutes apart - too close together for real travel
    between them. A behavioral anomaly rather than a threshold breach.
    """
    base_time = datetime.datetime.now(datetime.timezone.utc)
    user = "t.williams@contoso-lab.com"

    events = [
        {
            "TimeGenerated": _iso(base_time, 0),
            "UserPrincipalName": user,
            "SourceIP": "51.140.23.10",
            "ResultType": "Success",
            "ResultDescription": "Sign-in succeeded",
            "Location": "London, GB",
            "AppDisplayName": SYNTHETIC_APP,
        },
        {
            "TimeGenerated": _iso(base_time, 240),
            "UserPrincipalName": user,
            "SourceIP": "103.21.244.10",
            "ResultType": "Success",
            "ResultDescription": "Sign-in succeeded",
            "Location": "Singapore, SG",
            "AppDisplayName": SYNTHETIC_APP,
        },
    ]

    return events


def main() -> int:
    credential = AzureCliCredential()
    client = LogsIngestionClient(endpoint=DCE_ENDPOINT, credential=credential)

    logs = (
        generate_bruteforce_logs()
        + generate_password_spray_logs()
        + generate_impossible_travel_logs()
    )

    try:
        client.upload(rule_id=DCR_IMMUTABLE_ID, stream_name=STREAM_NAME, logs=logs)
    except HttpResponseError as e:
        print(f"Ingestion failed: {e.message}", file=sys.stderr)
        print(
            "\nCommon causes:\n"
            "  - STREAM_NAME doesn't match the DCR's streamDeclarations key\n"
            "  - the signed-in account (az login) doesn't have Monitoring "
            "Metrics Publisher on this DCR\n"
            "  - a field name/type here doesn't match the table schema",
            file=sys.stderr,
        )
        return 1

    print(f"Uploaded {len(logs)} synthetic log records to stream '{STREAM_NAME}'.")
    print("Scenarios: brute force, password spray, impossible travel.")
    print("Data typically takes a few minutes to become queryable in Log Analytics.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
